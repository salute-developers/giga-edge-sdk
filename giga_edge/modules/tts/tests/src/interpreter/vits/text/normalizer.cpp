constexpr const char* kDataRoot = "data/vits";
constexpr const char* kTextDirectory = "text/ru";

const TextNormalizer& Normalizer() {
  static const TextNormalizer normalizer(*CreateDataReader(kDataRoot), kTextDirectory);
  return normalizer;
}

struct Case {
  const char* text;
  const char* expected;
};

// The sentences joined by spaces.
std::string Normalize(std::string_view text) {
  std::string joined;
  for (const auto& sentence : Normalizer().Normalize(text)) {
    joined += (joined.empty() ? "" : " ") + sentence.text;
  }
  return joined;
}

void CheckCases(const std::vector<Case>& cases) {
  for (const auto& test_case : cases) {
    INFO(test_case.text);
    CHECK(Normalize(test_case.text) == test_case.expected);
  }
}

std::string ReadDataFile(const std::string& name) {
  std::ifstream file(std::string(kDataRoot) + "/" + kTextDirectory + "/" + name);
  std::stringstream text;
  text << file.rdbuf();
  return text.str();
}

// Files in memory, by path.
class MapReader : public IDataReader {
public:
  explicit MapReader(std::map<std::string, std::string> files)
    : files_(std::move(files)) {}

  IMovableDataSpanPtr ReadTransientData(const std::string& file_path) override {
    const auto found = files_.find(file_path);
    if (found == files_.end()) {
      return nullptr;
    }
    return data_reader::Create<IMovableDataSpanPtr>(std::vector<char>(found->second.begin(), found->second.end()));
  }

  IDataSpanPtr ReadPersistentData(const std::string& file_path) override {
    return ReadTransientData(file_path);
  }

private:
  std::map<std::string, std::string> files_;
};

std::string LoadError(
  const std::string& nouns,
  const std::string& units,
  const std::string& readings = "",
  const std::string& abbreviations = "",
  const std::string& words = "",
  const std::string& government = ""
) {
  MapReader reader(
    {{"ru/nouns.tsv", nouns},
     {"ru/units.tsv", units},
     {"ru/readings.tsv", readings},
     {"ru/abbreviations.tsv", abbreviations},
     {"ru/words.tsv", words},
     {"ru/government.tsv", government}}
  );
  try {
    TextNormalizer normalizer(reader, "ru");
  } catch (const std::exception& error) {
    return error.what();
  }
  return {};
}

