  auto cut_and_trusted = WithHomographModel(0.0, {{"homographs_vocab.txt", with_positions("[positions]\t25\n")}});
  REQUIRE(cut_and_trusted.Stress("включил свет , замок").back().source == StressSource::HOMOGRAPH_MODEL);
