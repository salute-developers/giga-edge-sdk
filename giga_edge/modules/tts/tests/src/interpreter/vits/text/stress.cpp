std::string Text(const std::string& text, const TextRange& range) {
  return text.substr(range.begin, range.size);
}

std::string Repeat(const std::string& text, size_t times) {
  std::string result;
  for (size_t i = 0; i < times; ++i) {
    result += text;
  }
  return result;
}

// plain of a sentence whose letters are all in the alphabet: marked in lower case without the pauses.
std::string PlainOf(const std::string& marked) {
  std::string plain;
  for (size_t pos = 0; pos < marked.size();) {
    const auto symbol = DecodeUtf8(marked, pos);
    const bool upper = (symbol.value >= U'А' && symbol.value <= U'Я') || symbol.value == U'Ё';
    if (upper) {
      const char32_t lower = symbol.value == U'Ё' ? U'ё' : symbol.value + 0x20;
      plain += static_cast<char>(0xC0 | (lower >> 6));
      plain += static_cast<char>(0x80 | (lower & 0x3F));
    } else if (symbol.value != U'^') {
      plain.append(marked, pos, symbol.size);
    }
    pos += symbol.size;
  }
  return plain;
}

bool HasVowel(const std::string& word, bool upper) {
  for (size_t pos = 0; pos < word.size();) {
    const auto symbol = DecodeUtf8(word, pos);
    const bool is_upper = (symbol.value >= U'А' && symbol.value <= U'Я') || symbol.value == U'Ё';
    const char32_t lower = symbol.value == U'Ё' ? U'ё' : (is_upper ? symbol.value + 0x20 : symbol.value);
    if (IsVowel(lower) && (is_upper || !upper)) {
      return true;
    }
    pos += symbol.size;
  }
  return false;
}

void CheckCases(Stresser& stresser, const Case* begin, const Case* end) {
  for (const auto* test = begin; test != end; ++test) {
    CAPTURE(test->text);
    const auto items = stresser.Stress(test->text);
    REQUIRE(StressedText(items) == test->stressed);
    const auto sentence = stresser.Prepare(test->text, kAlphabet);
    REQUIRE(sentence.marked == test->marked);
    REQUIRE(sentence.plain == (test->plain != nullptr ? std::string(test->plain) : PlainOf(test->marked)));
    REQUIRE_NOTHROW(CheckWords(sentence));
    for (const char symbol : std::string("+§\t\n_~*")) {
      REQUIRE(sentence.marked.find(symbol) == std::string::npos);
      REQUIRE(sentence.plain.find(symbol) == std::string::npos);
    }
    // Every word with a vowel has a stress; the two spellings of a word have as many letters.
    for (const auto& word : sentence.words) {
      const auto marked = Text(sentence.marked, word.marked);
      CAPTURE(marked);
      REQUIRE(HasVowel(marked, true) == HasVowel(marked, false));
      REQUIRE(marked.size() == word.plain.size);
    }
  }
}

